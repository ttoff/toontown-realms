def getPropNameCaseInsensitive(name):
    for propName in (PropList.keys()):
        propLower = propName.lower()
        propStripped = propLower.replace(" ", "")
        if name.lower() == propLower or name == propStripped:
            return propName
    return None


class PropPool:
    notify = DirectNotifyGlobal.directNotify.newCategory('PropPool')

    @staticmethod
    def getProp(name: str) -> NodePath:
        PropPool.notify.debug(f'{name}: Loading {PropList[name][LIST_MODEL]}')
        mdl = base.loader.loadModel(PropList[name][LIST_MODEL])
        attribs = PropList[name][LIST_ATTRIBUTES]
        # If the prop is a node inside of a model instead of the full model itself
        if 'sub_node' in attribs:
            PropPool.notify.debug(f'{name}: Getting sub node {attribs["sub_node"]}')
            model = mdl.find('**/' + attribs['sub_node'])
            mdl.removeNode()
        else:
            model = mdl
        if 'texture' in attribs:
            texture = base.loader.loadTexture(attribs["texture"])
            model.setTexture(texture, 1)

        if 'hide_nodes' in attribs:
            if isinstance(attribs['hide_nodes'], str):
                PropPool.notify.debug(f'{name}: Removing {attribs["hide_nodes"]}')
                model.find('**/' + attribs['hide_nodes']).removeNode()
            else:
                for node in attribs['hide_nodes']:
                    PropPool.notify.debug(f'{name}: Removing {node}')
                    model.find('**/' + node).removeNode()

        if model.isEmpty():
            PropPool.notify.error(f'{name} returned an empty prop')
        if 'scale' in attribs:
            PropPool.notify.debug(f'{name}: Setting scale to {attribs["scale"]}')
            model.setScale(attribs['scale'])
        return model
