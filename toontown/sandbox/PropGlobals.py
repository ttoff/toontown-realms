def prop(type: str, model: str, **kwargs) -> Tuple[str, str, Dict[str, Any]]:
    """
    Convenience function to generate the tuple
    :param model: Model path; This is required even for special
           props which might not get a model passed so we can show it in the UI
    :param kwargs: Extra data for the prop; this is separate from modifiable data like 'activeAnim'

    :return: Tuple with all 3 elements
    """
    attribs = {}
    if 'attribs' in kwargs.keys():
        print(f'prop {model} has deprecated attribs definition')
        attribs = kwargs['attribs']
    for key in list(kwargs.keys()):
        if key == 'attribs':
            continue
        attribs[key] = kwargs[key]
    return type, model, attribs


